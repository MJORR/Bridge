/**
 * The three layouts a single post can be drawn in.
 *
 * All three are the same template and the same blocks. What differs is where
 * the featured image sits relative to the title, which is the only decision
 * that actually changes how a post reads:
 *
 *   classic  the image under the title, in the text column;
 *   cover    the image behind the title, full width;
 *   feature  the image beside the title, two up.
 *
 * ---- Why one template and not three files ---------------------------------
 *
 * Three `single-*.html` files would be three copies of six core blocks, and a
 * change to the byline would have to be made in all of them — with the Site
 * Editor able to fork any one into the database, where it stops following the
 * theme. The head of the article is a full-width band with a constrained inner
 * column, exactly as every section block is, and all three layouts are that one
 * structure under a different grid. So the choice is a class on <body> and a
 * stylesheet, not a template to resolve.
 *
 * ---- Why global and not per post ------------------------------------------
 *
 * Deliberately not registered in theme.json's `customTemplates`, which is what
 * would put a template picker on each post. A site whose posts are laid out
 * three different ways is a site with no article design; the decision belongs
 * to whoever owns the design system, once, which is what this record is.
 *
 * Filterable so a client build can add a fourth without a theme edit. The slugs
 * are what the token record stores and what the body class is built from, so a
 * filter that renames one strands the sites already using it.
 *
 * @return array<string, array<string, string>>
 */
function bridge_post_templates(): array
{
	return (array) apply_filters(
		'bridge_post_templates',
		array(
			'classic' => array(
				'name'        => __('Classic', 'bridge'),
				'description' => __('Title, byline, then the photograph across the text column. The most forgiving of the three — it reads correctly whatever shape the image is, and it is the only one that never crops.', 'bridge'),
			),
			'cover'   => array(
				'name'        => __('Cover', 'bridge'),
				'description' => __('The photograph full width with the title laid over it. The strongest opening, and the one that asks most of the image: it is cropped to a band, so a picture whose subject is at the edge will lose it.', 'bridge'),
			),
			'feature' => array(
				'name'        => __('Feature', 'bridge'),
				'description' => __('The photograph beside the title, two up, with the article below. Magazine-like, and the one to pick when headlines are long — the title has a column of its own to run down.', 'bridge'),
			),
		)
	);
}

