/**
 * Bridge design tokens — storage, resolution and sanitisation.
 *
 * The token record is the single source of truth for the site's design
 * system. It is resolved from three layers, lowest priority first:
 *
 *   1. bridge_token_defaults()   Hardcoded, always complete. The theme still
 *                                works if every other layer is missing.
 *   2. design/tokens.json        Per-client seed, committed to the repo. Where
 *                                a Figma export lands.
 *   3. bridge_theme_options      What an operator saved in the admin.
 *
 * The resolved array is then sanitised into a guaranteed-complete, valid
 * structure — every consumer can read it without defensive checks.
 *
 * Nothing here knows about theme.json. Compilation lives in inc/theme-json.php.
 *
 * @package Bridge
 */

