/**
 * The palette slugs the theme guarantees, in editor display order.
 *
 * Fixed by the theme, never by the client. Slugs are written into post content
 * as class names (`has-primary-color`, `has-surface-background-color`), so
 * renaming or removing one silently restyles every page that used it. Only the
 * hex and the display name are configurable.
 *
 * @return array<string, string> Slug => default display name.
 */
function bridge_palette_slugs(): array
{
	return array(
		'primary'    => 'Primary',
		'secondary'  => 'Secondary',
		'accent'     => 'Accent',
		'background' => 'Background',
		'surface'    => 'Surface',
		'text'       => 'Text',
	);
}

/**
 * A palette slug from untrusted input, or the fallback.
 *
 * The check is `is_string()` before the comparison rather than a cast after
 * it. A cast looks equivalent and is not: the options screen posts JSON, and
 * an array arriving where a slug belongs — a malformed request, an older
 * client, a hand-rolled REST call — makes `(string)` emit an "Array to string
 * conversion" warning before returning the useless value "Array". The
 * sanitiser's whole job is that nothing reaches the tokens except a value it
 * recognises, and a warning on the way to rejecting one is a bug in the
 * rejecting.
 *
 * @param mixed  $value    Candidate, from anywhere.
 * @param string $fallback Slug to use when the candidate is not one.
 * @return string A slug in bridge_palette_slugs().
 */
function bridge_pick_palette_slug($value, string $fallback): string
{
	if (! is_string($value) || ! isset(bridge_palette_slugs()[$value])) {
		return $fallback;
	}

	return $value;
}

/**
 * The hex a palette slug currently resolves to.
 *
 * Read from the token record rather than from the compiled global settings:
 * the tokens are the source, the palette in theme.json is a copy of them, and
 * a caller that wants to reason about a colour — pick a readable foreground
 * against it, most often — should ask the thing that decides rather than the
 * thing that was told.
 *
 * @param string $slug Palette slug.
 * @return string A `#rrggbb` value, or '' when the slug is not a theme colour.
 */
function bridge_palette_hex(string $slug): string
{
	$palette = bridge_get_tokens()['brand']['palette'];

	return isset($palette[$slug]['color']) ? (string) $palette[$slug]['color'] : '';
}

/**
 * The attachment id of the site's mask shape, or 0.
 *
 * Set in Theme Options → Templates, beside the logos, and stored on `brand`
 * rather than on any one region — see the note there.
 */
function bridge_mask_shape_id(): int
{
	return max(0, (int) (bridge_get_tokens()['brand']['maskShapeId'] ?? 0));
}

/**
 * The URL of the site's mask shape, or an empty string.
 *
 * Empty covers both "none chosen" and "chosen, then deleted from the media
 * library" — the caller has one thing to check, and either way there is no
 * shape to cut with, so the image renders whole.
 */
function bridge_mask_shape_url(): string
{
	$id = bridge_mask_shape_id();

	if ($id <= 0) {
		return '';
	}

	$url = wp_get_attachment_url($id);

	return is_string($url) ? $url : '';
}

/**
 * Spacing preset slugs generated by the theme's 7-step spacing scale.
 *
 * The step count is deliberately not configurable: WordPress derives these
 * slugs from it, and theme.json plus the SCSS layer reference them by name.
 * Changing the count would renumber every existing spacing choice.
 *
 * Cast back to strings: PHP turns the numeric keys of bridge_spacing_steps()
 * into integers, and the slugs are compared strictly against submitted values,
 * which arrive from REST as strings.
 *
 * @return string[]
 */
function bridge_spacing_slugs(): array
{
	return array_map('strval', array_keys(bridge_spacing_steps()));
