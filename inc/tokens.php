			'fg'    => 'background',
			'bg'    => 'primary',
			'label' => __('Inverted text', 'bridge'),
			'on'    => __('on Primary', 'bridge'),
			'min'   => 4.5,
			'note'  => __('The Inverted skin: the light foreground on the brand’s dark ground.', 'bridge'),
		),
		array(
			'fg'    => 'secondary',
			'bg'    => 'background',
			'label' => __('Links', 'bridge'),
			'on'    => __('on Background', 'bridge'),
			'min'   => 4.5,
			'note'  => __('Every link in running text.', 'bridge'),
		),
		array(
			'fg'    => 'secondary',
			'bg'    => 'surface',
			'label' => __('Links', 'bridge'),
			'on'    => __('on Surface', 'bridge'),
			'min'   => 4.5,
			'note'  => __('The same links, inside a Surface band.', 'bridge'),
		),
	);
}

/**
 * Measure every pair the palette produces.
 *
 * The same arithmetic the buttons already report, pointed at the palette that
 * feeds them — which is where an inaccessible site actually starts. A button
 * scheme can rescue itself by picking a different label; body text cannot,
 * because the two colours in the pair are both the operator's choice.
 *
 * So this reports rather than repairs. There is no safe automatic fix: the
 * theme cannot darken a brand colour on the client's behalf, and a design
 * system that silently overrode the palette would be worse than one that says
 * plainly which pair fails and by how much.
 *
 * @param array<string, mixed> $tokens A sanitised token set.
 * @return array<int, array<string, mixed>>
 */
function bridge_palette_audit(array $tokens): array
{
	$palette = $tokens['brand']['palette'];
	$checks  = array();

	foreach (bridge_palette_pairs() as $pair) {
		$fg    = (string) ($palette[$pair['fg']]['color'] ?? '#000000');
		$bg    = (string) ($palette[$pair['bg']]['color'] ?? '#ffffff');
		$ratio = bridge_contrast_ratio($fg, $bg);

		$checks[] = array(
			'label' => $pair['label'],
			'on'    => $pair['on'],
			'note'  => $pair['note'],
			'fg'    => strtolower($fg),
			'bg'    => strtolower($bg),
			'ratio' => $ratio,
			'min'   => $pair['min'],
			'pass'  => $ratio >= $pair['min'],
		);
	}

	return $checks;
}

/**
 * Measure each card surface against the band it is painted on.
 *
 * Two questions per ground, and only one of them is a success criterion:
 *
 *   `text`  The band's foreground against the card, at 4.5:1. A card inherits
 *           its text from the band rather than naming its own, so this is
 *           1.4.3 for every word inside a card — and it is the check that
 *           catches the classic failure, a light card colour chosen on a light
 *           band while the words stay in the band's dark foreground.
 *
 *   `band`  The card against the band behind it. Reported as a number and
 *           deliberately *not* graded, because there is no threshold to grade
 *           it against: a card is meant to be a quiet step from its ground —
 *           the shipped Light card is 1.09:1 — and the shadow and the corner
 *           are what make it a card. Held to the 3:1 a control would owe, all
 *           four defaults fail, which would put four red badges on a design
 *           nothing is wrong with and teach an operator to ignore the two that
 *           mean something.
 *
 *           `flat` is the case that does mean something: a card the same
 *           colour as its band *and* carrying no shadow is not a quiet step,
 *           it is nothing at all.
 *
 * @param array<string, mixed> $tokens A sanitised token set.
 * @return array<int, array<string, mixed>>
 */
function bridge_card_audit(array $tokens): array
{
	$palette = $tokens['brand']['palette'];
	$colors  = $tokens['cards']['colors'];
	$lifted  = 'none' !== $tokens['cards']['shadow'];
	$checks  = array();

	foreach (bridge_card_grounds() as $key => $entry) {
		$card   = (string) ($colors[$key] ?? $entry['default']);
		$ground = (string) ($palette[$entry['ground']]['color'] ?? '#ffffff');
		$text   = (string) ($palette[$entry['text']]['color'] ?? '#000000');

		$on_card = bridge_contrast_ratio($card, $text);
		$on_band = bridge_contrast_ratio($card, $ground);

		$checks[] = array(
			'key'   => (string) $key,
			'label' => $entry['label'],
			'card'  => strtolower($card),
			'text'  => array(
				'ratio' => $on_card,
				'min'   => 4.5,
				'pass'  => $on_card >= 4.5,
			),
			'band'  => array(
				'ratio' => $on_band,
				// Indistinguishable from its ground, with nothing lifting it.
				'flat'  => $on_band < 1.05 && ! $lifted,
			),
		);
	}

	return $checks;
}

/**
 * A hex colour, or the fallback — for input that may be neither.
 *
 * `sanitize_hex_color()` has two ways of saying no, and only one of them is
 * `null`: an empty string it treats as "no colour" and hands straight back. A
 * plain `??` catches the null and not the empty string, so `{"color": ""}` —
 * which is what a cleared field, a hand-edited option or a partial import
 * produces — survived into the palette as an empty string. That compiles to a
 * custom property with no value, and reads as black to the contrast maths, so
 * the failure showed up as a button whose measured contrast was a fiction.
 *
 * Non-scalars are rejected before the cast rather than after: `(string)` on an
 * array is the literal "Array", which is not a colour and is not an error
 * either.
 *
 * @param mixed  $value    Candidate colour.
 * @param string $fallback Used when the candidate is not a usable colour.
 * @return string A `#rgb` or `#rrggbb` value.
 */
function bridge_hex_or($value, string $fallback): string
{
	$hex = is_scalar($value) ? sanitize_hex_color((string) $value) : null;

	return (is_string($hex) && '' !== $hex) ? $hex : $fallback;
}

/**
 * Reduce arbitrary input to a complete, valid token set.
 *
 * Total by design: anything missing, malformed or out of range is replaced
 * with the default rather than rejected, so a half-filled REST payload or a
 * hand-edited option can never produce a broken design system. This is the
 * only place token input is trusted — validate on write, not on read.
 *
 * @param array<string, mixed> $raw Candidate tokens, possibly partial.
 * @return array<string, mixed>
 */
function bridge_sanitize_tokens(array $raw): array
{
	$defaults = bridge_token_defaults();

	// ---- Brand palette ----------------------------------------------------
	$palette     = array();
	$raw_palette = isset($raw['brand']['palette']) && is_array($raw['brand']['palette'])
		? $raw['brand']['palette']
		: array();

	foreach (bridge_palette_slugs() as $slug => $default_name) {
		$entry = isset($raw_palette[$slug]) && is_array($raw_palette[$slug]) ? $raw_palette[$slug] : array();

		$name = isset($entry['name']) && is_scalar($entry['name'])
			? sanitize_text_field((string) $entry['name'])
			: '';

		$palette[$slug] = array(
			// A leading # and 3 or 6 hex digits, or the default — which is the
			// guarantee every piece of downstream contrast maths and every
			// line of compiled CSS is written against.
			'color' => bridge_hex_or(
				$entry['color'] ?? null,
				$defaults['brand']['palette'][$slug]['color']
			),
			'name'  => '' !== $name ? $name : $default_name,
		);
	}

	// ---- Typography -------------------------------------------------------
	$raw_type = isset($raw['typography']) && is_array($raw['typography']) ? $raw['typography'] : array();
	$dt       = $defaults['typography'];

	$font_set = isset($raw_type['fontSet']) ? sanitize_key((string) $raw_type['fontSet']) : '';
	if (! isset(bridge_font_sets()[$font_set])) {
		$font_set = $dt['fontSet'];
	}

	// Google families are validated against the curated catalogue, never
	// accepted as free text: the name is interpolated into an outbound URL and
	// becomes a directory name on disk.
	$google_on = ! empty($raw_type['googleFonts']);

	// Validated per role, not against the whole catalogue: the heading and
	// body lists differ, and a face chosen for the wrong job is a mistake
	// worth catching here rather than shipping to a client's homepage.
	$google_family = static function ($value, string $role) use ($google_on): string {
		$family = is_string($value) ? trim($value) : '';

		if (! $google_on || '' === $family || ! function_exists('bridge_google_families_for')) {
			return '';
		}

		return in_array($family, bridge_google_families_for($role), true) ? $family : '';
	};

	$typography = array(
		'fontSet'           => $font_set,
		'googleFonts'       => $google_on,
		'googleHeading'     => $google_family($raw_type['googleHeading'] ?? '', 'heading'),
		'googleBody'        => $google_family($raw_type['googleBody'] ?? '', 'body'),
		'baseSize'          => bridge_clamp_token('typography', 'baseSize', $raw_type['baseSize'] ?? null, (float) $dt['baseSize']),
		'scaleRatio'        => bridge_clamp_token('typography', 'scaleRatio', $raw_type['scaleRatio'] ?? null, (float) $dt['scaleRatio']),
		'headingWeight'     => bridge_pick_token('typography', 'headingWeight', $raw_type['headingWeight'] ?? '', $dt['headingWeight']),
		'headingCase'       => bridge_pick_token('typography', 'headingCase', $raw_type['headingCase'] ?? '', $dt['headingCase']),
		'bodyLineHeight'    => bridge_clamp_token('typography', 'bodyLineHeight', $raw_type['bodyLineHeight'] ?? null, (float) $dt['bodyLineHeight']),
		'headingLineHeight' => bridge_clamp_token('typography', 'headingLineHeight', $raw_type['headingLineHeight'] ?? null, (float) $dt['headingLineHeight']),
	);

	// ---- Layout -----------------------------------------------------------
	$raw_layout = isset($raw['layout']) && is_array($raw['layout']) ? $raw['layout'] : array();
	$dl         = $defaults['layout'];

	$content_size = (int) round(bridge_clamp_token('layout', 'contentSize', $raw_layout['contentSize'] ?? null, (float) $dl['contentSize']));
	$wide_size    = (int) round(bridge_clamp_token('layout', 'wideSize', $raw_layout['wideSize'] ?? null, (float) $dl['wideSize']));

	// A wide width narrower than the content width makes `alignwide` visibly
	// smaller than the default column — always a mistake, never a choice.
	if ($wide_size < $content_size) {
		$wide_size = $content_size;
	}

	$layout = array(
		'contentSize'      => $content_size,
		'wideSize'         => $wide_size,
		'spacingBase'      => bridge_clamp_token('layout', 'spacingBase', $raw_layout['spacingBase'] ?? null, (float) $dl['spacingBase']),
		'spacingIncrement' => bridge_clamp_token('layout', 'spacingIncrement', $raw_layout['spacingIncrement'] ?? null, (float) $dl['spacingIncrement']),
		'blockGap'         => bridge_pick_token('layout', 'blockGap', $raw_layout['blockGap'] ?? '', $dl['blockGap']),
		'rootPadding'      => bridge_pick_token('layout', 'rootPadding', $raw_layout['rootPadding'] ?? '', $dl['rootPadding']),
		'sectionPadding'   => bridge_pick_token('layout', 'sectionPadding', $raw_layout['sectionPadding'] ?? '', $dl['sectionPadding']),
	);

	// ---- Icons ------------------------------------------------------------
	$raw_icons = isset($raw['icons']) && is_array($raw['icons']) ? $raw['icons'] : array();

	$icons = array(
		'weight' => bridge_pick_token('icons', 'weight', $raw_icons['weight'] ?? '', $defaults['icons']['weight']),
	);

	// ---- Buttons ----------------------------------------------------------
	$raw_buttons = isset($raw['buttons']) && is_array($raw['buttons']) ? $raw['buttons'] : array();
	$db          = $defaults['buttons'];

	$raw_button_colors = isset($raw_buttons['colors']) && is_array($raw_buttons['colors']) ? $raw_buttons['colors'] : array();
	$button_fills      = array();

	// Palette slugs, not hex codes. A button fill has to be a colour the brand
	// already has — that is what keeps it tracking a palette change instead of
	// becoming a seventh colour hiding in a settings record. Keyed by ground
	// for the reason the card colours are: a payload missing one gets the
	// default, and one naming a ground this theme does not paint is dropped.
	foreach (bridge_button_grounds() as $key => $entry) {
		$button_fills[$key] = bridge_pick_token('buttons', 'fill', $raw_button_colors[$key] ?? '', $entry['fill']);
	}

	$buttons = array(
		'skin'   => bridge_pick_token('buttons', 'skin', $raw_buttons['skin'] ?? '', $db['skin']),
		'colors' => $button_fills,
	);

	// ---- Cards ------------------------------------------------------------
	$raw_cards = isset($raw['cards']) && is_array($raw['cards']) ? $raw['cards'] : array();
	$dc        = $defaults['cards'];

	$raw_card_colors = isset($raw_cards['colors']) && is_array($raw_cards['colors']) ? $raw_cards['colors'] : array();
	$card_colors     = array();

	// Keyed by ground rather than accumulated from what was submitted, so a
	// payload missing a ground gets the default for it and a payload naming a
	// ground the theme does not paint is dropped.
	foreach (bridge_card_grounds() as $key => $entry) {
		$card_colors[$key] = strtolower(
			bridge_hex_or($raw_card_colors[$key] ?? null, $entry['default'])
		);
	}

	/**
	 * The per-style settings.
	 *
	 * Walked from `bridge_card_styles()` rather than from what was submitted,
	 * the same way the grounds above are: a payload missing a style gets that
	 * style's defaults, a payload naming a style the theme does not draw is
	 * dropped, and a field a style does not have is dropped even if the style
	 * is real. So a saved record can only ever describe styles that exist,
	 * with fields those styles actually take.
	 */
	$raw_card_styles = isset($raw_cards['styles']) && is_array($raw_cards['styles']) ? $raw_cards['styles'] : array();
	$style_options   = bridge_card_style_options();
	$card_styles     = array();

	foreach (bridge_card_styles() as $slug => $entry) {
		$submitted = isset($raw_card_styles[$slug]) && is_array($raw_card_styles[$slug])
			? $raw_card_styles[$slug]
			: array();

		$style = array();

		foreach ((array) ($entry['fields'] ?? array()) as $field) {
			$allowed = $style_options[$field] ?? array();
			$default = (string) ($entry[$field] ?? '');

			// A field with no option list is a field the theme cannot check,
			// and an unchecked string is what the sanitiser exists to prevent.
			if (! $allowed) {
				continue;
			}

			$value = is_scalar($submitted[$field] ?? null) ? (string) $submitted[$field] : '';

			$style[$field] = in_array($value, $allowed, true) ? $value : $default;
		}

		$card_styles[$slug] = $style;
	}

	$cards = array(
		'padding' => bridge_pick_token('cards', 'padding', $raw_cards['padding'] ?? '', $dc['padding']),
		// Stored as a whole number of pixels. A radius is read off a design at
		// integer precision and nothing downstream wants 6.4px.
		'radius'  => (int) round(bridge_clamp_token('cards', 'radius', $raw_cards['radius'] ?? null, (float) $dc['radius'])),
		'shadow'  => bridge_pick_token('cards', 'shadow', $raw_cards['shadow'] ?? '', $dc['shadow']),
		// Words, so a whole number: wp_trim_words() counts them and half a
		// word is not a length.
		'excerpt' => (int) round(bridge_clamp_token('cards', 'excerpt', $raw_cards['excerpt'] ?? null, (float) $dc['excerpt'])),
		'colors'  => $card_colors,
		'styles'  => $card_styles,
	);

	// ---- Structure --------------------------------------------------------
	$raw_header = isset($raw['header']) && is_array($raw['header']) ? $raw['header'] : array();
	$raw_footer = isset($raw['footer']) && is_array($raw['footer']) ? $raw['footer'] : array();

	// The nested groups, read once. Without these the `?? ` fallbacks below
	// silently swallow an undefined variable and every logo and button setting
	// resolves to its default no matter what was saved.
	$raw_logo  = isset($raw_header['logo']) && is_array($raw_header['logo']) ? $raw_header['logo'] : array();
	$raw_cta   = isset($raw_header['cta']) && is_array($raw_header['cta']) ? $raw_header['cta'] : array();
	$raw_menus = isset($raw_header['menus']) && is_array($raw_header['menus']) ? $raw_header['menus'] : array();

	// `ctaBar` was this setting's name before the strip stopped holding the call
	// to action. Either key switches the bar on, so a site saved before the
	// rename keeps its bar. Deliberately an OR rather than "new key wins":
	// the seed ships `topBar` too, so an absent-key test would always find the
	// new key present and never reach the old one. Nothing is stuck on — the
	// options page submits a complete draft, so the first save writes the
	// record without the legacy key and this stops mattering.
	$top_bar = ! empty($raw_header['topBar']) || ! empty($raw_header['ctaBar']);

	// `inverseId` was the light logo's name while it was only ever shown under
	// a transparent header. Read when the new key is absent or empty rather
	// than only when it is absent: the seed ships `lightId`, so the merge hands
	// the sanitiser both keys and a plain `??` would always stop at the new
	// one. Nothing is lost by the looser test — 0 means "no light logo", which
	// is exactly when the old key is worth consulting.
	$light_id = max(0, (int) ($raw_logo['lightId'] ?? 0));

	if ($light_id <= 0) {
		$light_id = max(0, (int) ($raw_logo['inverseId'] ?? 0));
	}

	$cta_label = sanitize_text_field((string) ($raw_cta['label'] ?? ''));
	// esc_url_raw rather than a bare string: this becomes an href, and a
	// javascript: URL in a header would run on every page.
	$cta_url = esc_url_raw((string) ($raw_cta['url'] ?? ''));

	// The button used to be implied by having filled in both fields. Records
	// written under that rule carry no `enabled` key, so infer it from the
	// fields rather than switching an existing site's button off on upgrade.
	$cta_enabled = array_key_exists('enabled', $raw_cta)
		? ! empty($raw_cta['enabled'])
		: ('' !== $cta_label && '' !== $cta_url);

	$header = array(
		'layout'          => bridge_pick_token('header', 'layout', $raw_header['layout'] ?? '', $defaults['header']['layout']),
		'topBar'          => ! empty($top_bar),
		// Structural validation only. Whether the id still points at a live
		// menu is a question for render time — a menu deleted after it was
		// chosen must not silently rewrite the stored setting to 0, or the
		// choice is lost the moment someone opens the options page.
		'menus'           => array(
			'primary' => max(0, (int) ($raw_menus['primary'] ?? 0)),
			'utility' => max(0, (int) ($raw_menus['utility'] ?? 0)),
		),
		'background'      => bridge_pick_token('header', 'background', $raw_header['background'] ?? '', $defaults['header']['background']),
		'backgroundColor' => isset(bridge_palette_slugs()[(string) ($raw_header['backgroundColor'] ?? '')])
			? (string) $raw_header['backgroundColor']
			: $defaults['header']['backgroundColor'],
		'contrast'        => bridge_pick_token('header', 'contrast', $raw_header['contrast'] ?? '', $defaults['header']['contrast']),
		'sticky'          => ! empty($raw_header['sticky']),
		'border'          => ! empty($raw_header['border']),
		'paddingBlock'    => (int) round(bridge_clamp_token('header', 'paddingBlock', $raw_header['paddingBlock'] ?? null, (float) $defaults['header']['paddingBlock'])),
		'logo'            => array(
			'id'      => max(0, (int) ($raw_logo['id'] ?? 0)),
			'lightId' => $light_id,
			'height'  => (int) round(bridge_clamp_token('header', 'logoHeight', $raw_logo['height'] ?? null, (float) $defaults['header']['logo']['height'])),
		),
		'cta'             => array(
			'enabled' => $cta_enabled,
			'label'   => $cta_label,
			'url'     => $cta_url,
		),
	);

	$footer = array(
		'style' => bridge_pick_token('footer', 'style', $raw_footer['style'] ?? '', $defaults['footer']['style']),
	);

	// ---- Site output ------------------------------------------------------
	$raw_site = isset($raw['site']) && is_array($raw['site']) ? $raw['site'] : array();

	// Cast rather than defaulted: a boolean's "missing" and "off" are the same
	// answer, so there is nothing for a fallback to disambiguate.
	$site = array(
		'feeds' => ! empty($raw_site['feeds']),
	);

	// ---- Blocks -----------------------------------------------------------
	$raw_blocks = isset($raw['blocks']) && is_array($raw['blocks']) ? $raw['blocks'] : array();

	// Sorted and de-duplicated so two records describing the same set are
	// byte-identical — the options page compares them to decide whether there
	// is anything to save.
	$block_names = static function ($value): array {
		$names = array();

		foreach ((array) $value as $name) {
			if (! is_string($name)) {
				continue;
			}

			$name = strtolower(trim($name));

			// namespace/name is the only shape a block name takes, and this
			// value ends up in comparisons against the block registry.
			if (preg_match('#^[a-z][a-z0-9-]*/[a-z][a-z0-9-]*$#', $name)) {
				$names[] = $name;
			}
		}

		$names = array_values(array_unique($names));
		sort($names);

		return $names;
	};

	$disabled = $block_names($raw_blocks['disabled'] ?? array());
	$enabled  = $block_names($raw_blocks['enabled'] ?? array());

	// The editor cannot function without a few of these, so switching them off
	// is not a choice the record is allowed to hold.
	$disabled = array_values(array_diff($disabled, bridge_required_blocks()));

	// Off wins: a block in both lists is a contradiction, and the safer
	// reading of a contradiction in a locked-down theme is the narrower one.
	$enabled = array_values(array_diff($enabled, $disabled));

	return array(
		'brand'      => array('palette' => $palette),
		'typography' => $typography,
		'icons'      => $icons,
		'buttons'    => $buttons,
		'cards'      => $cards,
		'header'     => $header,
		'footer'     => $footer,
		'layout'     => $layout,
		'blocks'     => array(
			'enabled'  => $enabled,
			'disabled' => $disabled,
		),
		'site'       => $site,
	);
}

/**
 * Persist a token set, sanitising first.
 *
 * The full sanitised structure is stored rather than a sparse diff, so the
 * record is self-describing and portable to another site.
 *
 * @param array<string, mixed> $tokens Candidate tokens, possibly partial.
 * @return bool True when the stored value changed.
 */
function bridge_update_tokens(array $tokens): bool
{
	return update_option(BRIDGE_TOKENS_OPTION, bridge_sanitize_tokens($tokens), true);
}

/**
 * Merge a partial token fragment into what is already stored.
 *
 * @param array<string, mixed> $fragment Partial tokens.
 * @return bool True when the stored value changed.
 */
function bridge_patch_tokens(array $fragment): bool
{
	return bridge_update_tokens(bridge_merge_deep(bridge_get_tokens(), $fragment));
}

/**
 * Short fingerprint of the current token set.
 */
function bridge_tokens_fingerprint(): string
{
	return substr(md5((string) wp_json_encode(bridge_get_tokens())), 0, 12);
}

/**
 * The stored token fingerprint, for versioning token-derived assets.
 */
function bridge_tokens_version(): string
{
	$version = get_option(BRIDGE_TOKENS_VERSION_OPTION, '');

	return is_string($version) && '' !== $version ? $version : bridge_tokens_fingerprint();
}

/**
 * Drop every cached copy of the design system after a token change.
 *
 * Three caches matter, and missing any one produces the classic "I saved it
 * but nothing changed" report:
 *
 *   - Our own request-level memo.
 *   - WordPress's resolved theme.json (static properties on the resolver).
 *   - The generated global stylesheet in the object cache, which persists
 *     across requests wherever Redis or Memcached is configured.
 *
 * wp_clean_theme_json_cache() covers the last two.
 */
function bridge_flush_tokens(): void
{
	bridge_tokens_memo(null, true);

	if (function_exists('wp_clean_theme_json_cache')) {
		wp_clean_theme_json_cache();
	}

	$tokens = bridge_get_tokens();

	update_option(BRIDGE_TOKENS_VERSION_OPTION, bridge_tokens_fingerprint(), true);

	/**
	 * Fires after the design tokens change and every cache has been dropped.
	 *
	 * Later phases hang font preloading and icon sprite regeneration here;
	 * hosting-level cache purges belong here too.
	 *
	 * @param array<string, mixed> $tokens The newly resolved token set.
	 */
	do_action('bridge_tokens_changed', $tokens);
}

/**
 * Flush whenever the token option is written, however it was written.
 *
 * Hooking the generic option actions rather than the option-specific ones
 * catches direct update_option() calls from WP-CLI, migrations and future
 * REST handlers alike. All three pass the option name as the first argument.
 *
 * @param string $option Option name that changed.
 */
function bridge_maybe_flush_tokens($option): void
{
	if (BRIDGE_TOKENS_OPTION === $option) {
		bridge_flush_tokens();
	}
}
