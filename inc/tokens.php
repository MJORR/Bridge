		'surface'  => array(
			'label'  => __('Surface', 'bridge'),
			'ground' => 'surface',
			'text'   => 'text',
			'fill'   => 'primary',
		),
		'accent'   => array(
			'label'  => __('Accent', 'bridge'),
			'ground' => 'accent',
			'text'   => 'text',
			// The accent band is already the loudest thing on the page, so its
			// button answers with weight rather than more colour.
			'fill'   => 'primary',
