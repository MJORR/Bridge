			// Below ~1.05 the scale collapses into one size; above 2.0 an h1
			// dwarfs a phone viewport even after fluid compression.
			'scaleRatio'        => array('min' => 1.05, 'max' => 2.0, 'step' => 0.005),
			'bodyLineHeight'    => array('min' => 1.1, 'max' => 2.2, 'step' => 0.05),
			'headingLineHeight' => array('min' => 0.9, 'max' => 1.8, 'step' => 0.05),
			'headingWeight'     => array('options' => array('300', '400', '500', '600', '700', '800', '900')),
			'headingCase'       => array('options' => array('none', 'uppercase')),
		),
		'icons'      => array(
			'weight' => array('options' => array('regular', 'bold')),
		),
		'header'     => array(
			// Every layout stacks or rows the same two elements; none puts the
			// menu in a fixed centre column, which would cap how many items it
			// can hold as a client's services grow.
			'layout'       => array('options' => array('left', 'centre', 'two-row')),
			'background'   => array('options' => array('solid', 'transparent')),
			'contrast'     => array('options' => array('auto', 'light', 'dark')),
			'logoHeight'   => array('min' => 16, 'max' => 120, 'step' => 2, 'unit' => 'px'),
			// 0 is a header whose logo touches the edges of its ground — flush
			// is a legitimate look, so it is a legitimate value. Above ~80 the
			// bar stops reading as a header and starts reading as a section.
			'paddingBlock' => array('min' => 0, 'max' => 80, 'step' => 2, 'unit' => 'px'),
		),
		'footer'     => array(
			'style' => array('options' => array('simple', 'columns')),
		),
		'layout'     => array(
			'contentSize'      => array('min' => 320, 'max' => 1600, 'step' => 10, 'unit' => 'px'),
			'wideSize'         => array('min' => 480, 'max' => 2400, 'step' => 10, 'unit' => 'px'),
			'spacingBase'      => array('min' => 0.5, 'max' => 4.0, 'step' => 0.25, 'unit' => 'rem'),
			'spacingIncrement' => array('min' => 1.1, 'max' => 2.0, 'step' => 0.05),
			'blockGap'         => array('options' => bridge_spacing_slugs()),
			'rootPadding'      => array('options' => bridge_spacing_slugs()),
			'sectionPadding'   => array('options' => bridge_spacing_slugs()),
		),
	);
