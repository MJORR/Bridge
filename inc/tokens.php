<?php

/**
 * Bridge design tokens — storage, resolution and sanitisation.
 *
 * The token record is the single source of truth for the site's design
 * system. It is resolved from three layers, lowest priority first:
 *
 *   1. bridge_token_defaults()   Hardcoded, always complete. The theme still
 *                                works if every other layer is missing.
 *   2. design/tokens.json        Per-client seed, committed to the repo. Where
 *                                a Figma export lands.
 *   3. bridge_theme_options      What an operator saved in the admin.
 *
 * The resolved array is then sanitised into a guaranteed-complete, valid
 * structure — every consumer can read it without defensive checks.
 *
 * Nothing here knows about theme.json. Compilation lives in inc/theme-json.php.
 *
 * @package Bridge
 */

declare(strict_types=1);

if (! defined('ABSPATH')) {
	exit;
}

/**
 * Where operator-saved values live. Autoloaded — it is read on every request.
 */
define('BRIDGE_TOKENS_OPTION', 'bridge_theme_options');

/**
 * Fingerprint of the current token set, refreshed whenever tokens change.
 *
 * Not a cache-buster for dist/main.css — that file compiles no token values,
 * it only references the CSS custom properties WordPress prints inline. This
 * is a change signal for token-derived artefacts that arrive in later phases
 * (font preloads, the icon sprite) and for external cache purging.
 */
define('BRIDGE_TOKENS_VERSION_OPTION', 'bridge_tokens_version');

/**
 * The palette slugs the theme guarantees, in editor display order.
 *
 * Fixed by the theme, never by the client. Slugs are written into post content
 * as class names (`has-primary-color`, `has-surface-background-color`), so
 * renaming or removing one silently restyles every page that used it. Only the
 * hex and the display name are configurable.
 *
 * @return array<string, string> Slug => default display name.
 */
function bridge_palette_slugs(): array
{
	return array(
		'primary'    => 'Primary',
		'secondary'  => 'Secondary',
		'accent'     => 'Accent',
		'background' => 'Background',
		'surface'    => 'Surface',
		'text'       => 'Text',
	);
}

/**
 * The hex a palette slug currently resolves to.
 *
 * Read from the token record rather than from the compiled global settings:
 * the tokens are the source, the palette in theme.json is a copy of them, and
 * a caller that wants to reason about a colour — pick a readable foreground
 * against it, most often — should ask the thing that decides rather than the
 * thing that was told.
 *
 * @param string $slug Palette slug.
 * @return string A `#rrggbb` value, or '' when the slug is not a theme colour.
 */
function bridge_palette_hex(string $slug): string
{
	$palette = bridge_get_tokens()['brand']['palette'];

	return isset($palette[$slug]['color']) ? (string) $palette[$slug]['color'] : '';
}

/**
 * Spacing preset slugs generated by the theme's 7-step spacing scale.
 *
 * The step count is deliberately not configurable: WordPress derives these
 * slugs from it, and theme.json plus the SCSS layer reference them by name.
 * Changing the count would renumber every existing spacing choice.
 *
 * Cast back to strings: PHP turns the numeric keys of bridge_spacing_steps()
 * into integers, and the slugs are compared strictly against submitted values,
 * which arrive from REST as strings.
 *
 * @return string[]
 */
function bridge_spacing_slugs(): array
{
	return array_map('strval', array_keys(bridge_spacing_steps()));
}

/**
 * The spacing scale, slug to the name an operator sees.
 *
 * The slugs are numbers because WordPress derives them from the step count and
 * writes them into post content; the names are t-shirt sizes because "L" is a
 * thing a person can choose between and `spacing--70` is not. One scale, named
 * once, offered by every control that spends spacing — block gap, page side
 * padding, section padding — so a site can be tightened or opened up by moving
 * several settings through the same vocabulary.
 *
 * @return array<string, string> Slug => display name, smallest first.
 */
function bridge_spacing_steps(): array
{
	return array(
		'20' => 'XS',
		'30' => 'S',
		'40' => 'M',
		'50' => 'L',
		'60' => 'XL',
		'70' => '2XL',
		'80' => '3XL',
	);
}

/**
 * The valid range or option set for every numeric and enumerated token.
 *
 * One source of truth, consumed by both the sanitiser and the REST route that
 * feeds the options page. Split across two definitions, a slider would sooner
 * or later offer a value the server silently clamps — which reads to the
 * operator as the page ignoring them.
 *
 * @return array<string, array<string, array<string, mixed>>>
 */
function bridge_token_constraints(): array
{
	return array(
		'typography' => array(
			// Below 0.75rem body copy stops being readable; above 1.5rem the
			// fluid clamps at the top of the scale start to overlap.
